-- customer city with purchased product category
SELECT
    c.customer_city,
    o.order_id,
    p.product_category_name,
    oi.price
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
JOIN order_items oi
ON o.order_id = oi.order_id
JOIN products p
ON oi.product_id = p.product_id;

-- top cities by total revenue
SELECT
    c.customer_city,
    ROUND(SUM(oi.price),2) AS total_revenue
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
JOIN order_items oi
ON o.order_id = oi.order_id
GROUP BY c.customer_city
ORDER BY total_revenue DESC
LIMIT 10;

-- total orders by product category
SELECT
    p.product_category_name,
    COUNT(oi.order_id) AS total_orders
FROM order_items oi
JOIN products p
ON oi.product_id = p.product_id
GROUP BY p.product_category_name
ORDER BY total_orders DESC;

-- average revenue per category
SELECT
    p.product_category_name,
    ROUND(AVG(oi.price),2) AS avg_revenue
FROM order_items oi
JOIN products p
ON oi.product_id = p.product_id
GROUP BY p.product_category_name
ORDER BY avg_revenue DESC;

-- top 10 most expensive ordered products
SELECT
    p.product_category_name,
    oi.price
FROM order_items oi
JOIN products p
ON oi.product_id = p.product_id
ORDER BY oi.price DESC
LIMIT 10;

-- customer states with highest orders
SELECT
    c.customer_state,
    COUNT(o.order_id) AS total_orders
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY c.customer_state
ORDER BY total_orders DESC;

-- revenue generated by each state
SELECT
    c.customer_state,
    ROUND(SUM(oi.price),2) AS total_revenue
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
JOIN order_items oi
ON o.order_id = oi.order_id
GROUP BY c.customer_state
ORDER BY total_revenue DESC;